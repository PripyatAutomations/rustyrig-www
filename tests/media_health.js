const assert=require('node:assert/strict');
const {rrMediaObserve}=require('../js/webui.media.health.js');
const state={};
const frame={stream:1,dir:0,codec:'opus',ts:100000000,seq:0xffffffff};
let result=rrMediaObserve(state,frame,1000000);
assert(result.accept && !result.discontinuity && result.feedback.media.quality===100);
frame.seq=0; frame.ts+=20000;
assert(rrMediaObserve(state,frame,1020000).accept);
assert(!rrMediaObserve(state,frame,1020001).accept);
frame.seq=2;frame.ts+=20000;
assert(rrMediaObserve(state,frame,1060000).discontinuity);
frame.seq=1;frame.ts-=20000;
assert(!rrMediaObserve(state,frame,1060001).accept);
frame.seq=3;frame.ts+=40000;
assert.equal(rrMediaObserve(state,frame,2000000).feedback.media.quality,75);
frame.seq=4;frame.ts+=20000;
assert.equal(rrMediaObserve(state,frame,3000000).feedback.media.quality,50);
frame.stream=2;
assert(!rrMediaObserve(state,frame,4000000).discontinuity);
for(let i=3;i<20;i++) rrMediaObserve(state,{...frame,stream:i},4000000+i);
assert.equal(state.flows.size,8);
console.log('PASS: browser media feedback, relative timing, sequence wrap/gaps, duplicates and bounded stream observations');
